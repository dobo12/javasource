package objetc;

public class Mymath {
    long add(long a, long b) {
        return a + b;
    }

    long subtract(long a, long b) {
        return a - b;
    }

    long multiply(long a, long b) {
        return a * b;
    }

    double dibide(double a, double b) {
        return a / b;
    }

}
